/* ============================================================
 *  根据天气名查找图标
 *  输入 "Clear"  → 返回指向 "晴" 图标的指针
 *  输入 "Haze"   → 返回 NULL（表里没有）
 * ============================================================ */
const weather_icon_t *weather_icon_get(const char *name)
{
    if (name == NULL) return NULL;

    for (uint32_t i = 0; i < WEATHER_ICON_COUNT; i++)
    {
        if (strcmp(g_weather_icons[i].name, name) == 0)
        {
            return &g_weather_icons[i];
        }
    }
    return NULL;
}

/**
  * @brief  OLED初始化
  * @param  无
  * @retval 无
  */
void OLED_Init(void)
{
	uint32_t i, j;
	
	for (i = 0; i < 1000; i++)			//上电延时
	{
		for (j = 0; j < 1000; j++);
	}
	
	OLED_I2C_Init();			//端口初始化
	
	OLED_WriteCommand(0xAE);	//关闭显示
	
	OLED_WriteCommand(0xD5);	//设置显示时钟分频比/振荡器频率
	OLED_WriteCommand(0x80);
	
	OLED_WriteCommand(0xA8);	//设置多路复用率
	OLED_WriteCommand(0x3F);
	
	OLED_WriteCommand(0xD3);	//设置显示偏移
	OLED_WriteCommand(0x00);
	
	OLED_WriteCommand(0x40);	//设置显示开始行
	
	OLED_WriteCommand(0xA1);	//设置左右方向，0xA1正常 0xA0左右反置
	
	OLED_WriteCommand(0xC8);	//设置上下方向，0xC8正常 0xC0上下反置

	OLED_WriteCommand(0xDA);	//设置COM引脚硬件配置
	OLED_WriteCommand(0x12);
	
	OLED_WriteCommand(0x81);	//设置对比度控制
	OLED_WriteCommand(0xCF);

	OLED_WriteCommand(0xD9);	//设置预充电周期
	OLED_WriteCommand(0xF1);

	OLED_WriteCommand(0xDB);	//设置VCOMH取消选择级别
	OLED_WriteCommand(0x30);

	OLED_WriteCommand(0xA4);	//设置整个显示打开/关闭

	OLED_WriteCommand(0xA6);	//设置正常/倒转显示

	OLED_WriteCommand(0x8D);	//设置充电泵
	OLED_WriteCommand(0x14);

	OLED_WriteCommand(0xAF);	//开启显示
		
	OLED_Clear();				//OLED清屏
}

/**
  * @brief  OLED 显示位图（支持自动对齐与裁剪）
  * @param  x: 起始列坐标（0~127）
  * @param  y: 起始像素行坐标（0~63）
  * @param  width: 图像宽度（像素）
  * @param  height: 图像高度（像素）
  * @param  bitmap: 图像数据指针（每列每页排布）
  * @retval 无
  */
void OLED_DrawBitmap(uint8_t x, uint8_t y, uint8_t width, uint8_t height, const uint8_t *bitmap)
{
    uint8_t page_start, page_count;
    uint8_t x_end;
    uint32_t raw_size;
    uint32_t j = 0;

    // 起始页处理（每页8行，向上对齐）
    if ((y % 8) != 0)
    {
        y = (y / 8 + 1) * 8;
    }
    page_start = y / 8;

    // 图像页数，非8倍高度自动补页
    page_count = (height + 7) / 8;

    // 列范围裁剪
    if (x >= 128) return;
    if (x + width > 128) width = 128 - x;

    // 行范围裁剪
    if (page_start >= 8) return;
    if (page_start + page_count > 8) page_count = 8 - page_start;

    // 数据总量限制
    raw_size = width * page_count;
    if (raw_size > 1024) raw_size = 1024;

    x_end = x + width;

    // 分页写入图像数据
    for (uint8_t page = 0; page < page_count; page++)
    {
		OLED_SetCursor(page_start + page, x); // 设置页地址和列地址

        for (uint8_t col = x; col < x_end; col++)
        {
            OLED_WriteData(bitmap[j++]);          // 写入数据
            if (j >= raw_size)
                return;  // 数据发送完毕
        }
    }
}
